#!/usr/bin/env python3
"""Boss-round evidence from engine recordings (run_godot_checks.ps1 -Record -RecordRound r05 -RecordUntilEnd
-InjectEnd win|loss -RecordTag r05_win|r05_loss). Owner: 05-audio.

For each recording: confirms from the cue log that boss_incoming, wave_cleared and the ending stinger were
played by the engine path, measures the music duck around the boss warning (Music bus gain log), and level /
clipping / SFX-vs-music masking in the 30 s window that ends 4 s after the stinger starts. Writes one 30 s
MP3 per recording (exact engine Master output, 0.3 s fades only) and docs/audio/BOSS_ROUND_REPORT.md.
"""
from __future__ import annotations

import json
import math
import shutil
import subprocess
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from mix_report import integrated_lufs, lufs_series, read, db  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
LISTEN = ROOT / "docs/audio/previews/listen"
RUNS = [("r05_win_s7_a5", "boss_to_victory_30s.mp3"), ("r05_loss_s7", "boss_to_defeat_30s.mp3")]
# A/B for the off-screen attenuation decision (same probe seed 7, win injected at 115 s)
AB = [("r05_win_s7_a9", 9.0), ("r05_win_s7_a5", 5.0)]


def main() -> int:
    L = ["# BOSS_ROUND_REPORT.md — boss round recorded through the engine (generated by tools/audio/boss_report.py)", "",
         "Round r05 (scripted boss wave at t = 95 s), project Audio autoload + 02 `Events.sfx` emitters + scripted player "
         "(sandbox AudioProbe), headless Dummy driver, Master recorded after the limiter. The battle END was a sandbox "
         "test injection at battle t = 115 s (`BattleSim._damage_base(...)` → real `_end` → App result → "
         "`Events.battle_ended` → bridge stinger), so the ending is engine-path but not earned by play. The boss warning "
         "and wave_cleared events were NOT injected.", ""]
    for tag, mp3 in RUNS:
        d = ROOT / f"tools/audio/_render/recording_{tag}"
        meta = json.loads((d / "rec_meta.json").read_text(encoding="utf-8"))
        rep = json.loads((d / "audio_integration_report.json").read_text(encoding="utf-8"))
        sr, master = read(d / "rec_master.wav")
        _, sfx = read(d / "rec_sfx.wav"); _, ui = read(d / "rec_ui.wav"); _, music = read(d / "rec_music.wav")
        n = min(len(master), len(sfx), len(ui), len(music))
        master, fx, music = master[:n], (sfx + ui)[:n], music[:n]
        scale = (n / sr) / float(meta["seconds"])          # audio clock / wall clock (Dummy driver drift)
        cue = lambda name: [round(c[0], 2) for c in meta["cues"] if c[1] == name]
        boss, stw, std, wc = cue("boss_incoming"), cue("stinger_win"), cue("stinger_defeat"), cue("wave_cleared")
        sting = (stw or std or [None])[0]
        g = np.array([[x[0], x[1]] for x in meta["music_gain"]])
        base_gain = float(np.median(g[(g[:, 0] > 5) & (g[:, 0] < 90), 1]))
        duck = None
        if boss:
            w = g[(g[:, 0] >= boss[0]) & (g[:, 0] <= boss[0] + 2.0), 1]
            duck = round(float(w.min()) - base_gain, 2) if len(w) else None
        end_a = (sting * scale + 4.0) if sting else n / sr
        a0 = max(0.0, end_a - 30.0)
        s0, s1 = int(a0 * sr), int(min(n, end_a * sr))
        seg = master[s0:s1]
        gain_db = np.interp(np.arange(n) / sr, g[:, 0] * scale, g[:, 1])
        mu = (music * (10 ** (gain_db / 20))[:, None])[s0:s1]
        _, fxm = lufs_series(fx[s0:s1], sr, 0.4, 0.1)
        _, mum = lufs_series(mu, sr, 0.4, 0.1)
        act = fxm > -45
        buried = int(np.sum(act & (fxm - mum <= 0)))
        pk = float(np.abs(seg).max())
        clipped = int(np.sum(np.abs(seg) >= 32767 / 32768))
        il = integrated_lufs(seg, sr)
        # stinger level vs the battle music it replaces (music fades 0.25 s before the stinger)
        st_db = None
        if sting:
            t = sting * scale
            a, b = int((t + 0.3) * sr), int((t + 2.3) * sr)
            c, e = int((t - 6.0) * sr), int((t - 1.0) * sr)
            st_db = round(db(float(np.sqrt(np.mean(master[a:b] ** 2)))) - db(float(np.sqrt(np.mean(master[c:e] ** 2)))), 1)
        LISTEN.mkdir(parents=True, exist_ok=True)
        subprocess.run([shutil.which("ffmpeg"), "-hide_banner", "-loglevel", "error", "-y", "-ss", f"{a0:.3f}", "-t", f"{end_a - a0:.3f}",
                        "-i", str(d / "rec_master.wav"), "-af", f"afade=t=in:d=0.3,afade=t=out:st={end_a - a0 - 0.3:.3f}:d=0.3",
                        "-map_metadata", "-1", "-c:a", "libmp3lame", "-b:a", "192k", str(LISTEN / mp3)], check=True)
        L += [f"## {tag} → `previews/listen/{mp3}` ({a0:.1f}–{end_a:.1f} s of the recording)",
              f"- Result: {'win' if meta['results'] and meta['results'][0]['won'] else 'loss'} (injected at battle t {meta['end_injected'].get('at_battle_t')} s); "
              f"battle_ended at recording t {meta['battle_ended_at']:.2f} s.",
              f"- Engine-path cue log: boss_incoming at {boss} s, wave_cleared at {wc} s, stinger_win {stw}, stinger_defeat {std}.",
              f"- Music duck during the boss warning: {duck} dB vs the battle level ({base_gain:.2f} dB bus gain); manifest asks −8 dB.",
              f"- Stinger vs preceding battle mix (RMS, 2 s vs 5 s): {st_db:+.1f} dB." if st_db is not None else "- No stinger.",
              f"- 30 s window: integrated {il:.1f} LUFS, sample peak {db(pk):.2f} dBFS, full-scale samples {clipped}; "
              f"SFX buried under music in {buried}/{int(act.sum())} active 400 ms windows.",
              f"- Voices: peak SFX {rep['max_active_sfx']}/12; same-frame duplicate cues {len(rep['same_frame_duplicates'])}.", ""]
        print(tag, "boss", boss, "sting", sting, "duck", duck, "st_db", st_db, "il", round(il, 1), "pk", round(db(pk), 2), "clip", clipped, "buried", buried, int(act.sum()))
    L += ["## Off-screen attenuation A/B (decision for v3.1)", "",
          "Same round, probe seed 7 (fixes App\u2019s randi() battle seed), same injected ending; only the maximum off-screen attenuation differs. "
          "The camera follows the hero, so the frontline is often off-screen; at −9 dB those fights sank under the music.", "",
          "| Max off-screen attenuation | SFX buried under music (400 ms windows, whole recording) | Before the boss (t < 95 s) | Attenuated cues | Kills |", "|---|---|---|---|---|"]
    for tag, att in AB:
        d = ROOT / f"tools/audio/_render/recording_{tag}"
        meta = json.loads((d / "rec_meta.json").read_text(encoding="utf-8"))
        rep = json.loads((d / "audio_integration_report.json").read_text(encoding="utf-8"))
        sr, _m = read(d / "rec_master.wav"); _, s_ = read(d / "rec_sfx.wav"); _, u_ = read(d / "rec_ui.wav"); _, mu_ = read(d / "rec_music.wav")
        n = min(len(_m), len(s_), len(mu_)); sc = (n / sr) / float(meta["seconds"])
        g = np.array([[x[0], x[1]] for x in meta["music_gain"]])
        mu_ = mu_[:n] * (10 ** (np.interp(np.arange(n) / sr, g[:, 0] * sc, g[:, 1]) / 20))[:, None]
        t, f = lufs_series((s_ + u_)[:n], sr, 0.4, 0.1); _, mm = lufs_series(mu_, sr, 0.4, 0.1)
        act = f > -45; pre = act & (t < 95)
        L.append(f"| −{att:.0f} dB | {int(np.sum(act & (f - mm <= 0)))}/{int(act.sum())} ({np.sum(act & (f - mm <= 0)) / act.sum():.1%}) | "
                 f"{int(np.sum(pre & (f - mm <= 0)))}/{int(pre.sum())} | {rep['audio_snapshot']['attenuated_offscreen']} | {rep['engine_truth']['kills']} |")
    L += ["", "Decision: default `OFFSCREEN_MAX_ATTEN_DB` 9 → 5 dB (src/audio/audio_manager.gd). Off-screen fights stay a little quieter "
          "than on-screen ones but remain audible. Not judged by a listener.", ""]
    L += ["## Limits", "- The ending was injected (see above). Earned wins/losses in r05 take longer than the bounded run.",
          "- Headless Dummy driver: no device output stage, speaker or OS mixer. Nobody has listened yet."]
    (ROOT / "docs/audio/BOSS_ROUND_REPORT.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
